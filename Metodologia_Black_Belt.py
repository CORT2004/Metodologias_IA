#General Electric (GE) fue una de las empresas que popularizó Six Sigma en los años 90 bajo el liderazgo de Jack Welch.
#GE utilizó Six Sigma en:

#Procesos de manufactura
#-Reducción de defectos en producción
#-Mejora en calidad de productos

#Procesos administrativos
#-Optimización de tiempos
#-Reducción de errores operativos

#Impacto real: Según GE:

#-Ahorros de miles de millones de dólares
#-Mejora significativa en eficiencia

#Ejemplo simplificado dentro de GE:
#_Problema: muchas fallas en un producto
#Black Belt hace:

#Define → identifica el problema
#Measure → mide cuántos defectos hay
#Analyze → detecta la causa (máquina, proceso, etc.)
#Improve → corrige el proceso
#Control → monitorea que no vuelva a fallar


